-- Schema is owned by Flyway. Hibernate only VALIDATES it (spring.jpa.hibernate.ddl-auto=validate).
-- Every sequence uses INCREMENT BY 50 to match @SequenceGenerator(allocationSize = 50):
-- the pooled optimizer hands out 50 ids per nextval() call, and a mismatch fails startup.

create sequence categories_seq increment by 50;
create table categories (
    id   bigint primary key,
    name varchar(100) not null unique
);

create sequence products_seq increment by 50;
create table products (
    id          bigint primary key,
    sku         varchar(40)    not null unique,
    name        varchar(200)   not null,
    price       numeric(12, 2) not null,
    stock       integer        not null check (stock >= 0), -- last line of defence against overselling
    version     bigint         not null,                    -- @Version optimistic lock counter
    category_id bigint         not null references categories (id),
    deleted     boolean        not null default false       -- Hibernate @SoftDelete flag
);
create index products_category_idx on products (category_id);

create sequence customers_seq increment by 50;
create table customers (
    id         bigint primary key,
    name       varchar(100) not null,
    email      varchar(200) not null unique,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);

create sequence orders_seq increment by 50;
create table orders (                                       -- "order" is a reserved word, hence "orders"
    id          bigint primary key,
    customer_id bigint not null references customers (id),
    placed_at   timestamp(6) with time zone not null
);
create index orders_customer_idx on orders (customer_id);   -- Postgres does NOT index FKs for you

create sequence order_lines_seq increment by 50;
create table order_lines (
    id         bigint primary key,
    order_id   bigint         not null references orders (id),
    product_id bigint         not null references products (id),
    quantity   integer        not null check (quantity > 0),
    unit_price numeric(12, 2) not null
);
create index order_lines_order_idx on order_lines (order_id);

-- IDENTITY on purpose: shows that IDENTITY ids disable JDBC insert batching.
create table audit_log (
    id         bigint generated by default as identity primary key,
    message    varchar(500) not null,
    created_at timestamp(6) with time zone not null
);

create sequence tags_seq increment by 50;
create table tags (
    id   bigint primary key,
    name varchar(50) not null
);
